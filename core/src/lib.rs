//! BuzzInstaller core.
//!
//! Owns everything that is not pixels: `BZ://` link parsing, chunk planning,
//! hashing, and (from phase 2) the BuzzHeavier HTTP client.
//!
//! The crate builds and tests standalone with `cargo test`. The
//! `flutter_rust_bridge` surface is behind the optional `bridge` feature so the
//! crate stays usable from plain Rust (CLI tools, tests) without codegen.

pub mod chunking;
pub mod error;
pub mod hash;
pub mod link;

pub use chunking::{
    chunk_count, chunk_name, clamp_chunk_size, describe_chunk_plan, plan_chunks,
    sanitize_filename, ChunkSpec, DEFAULT_CHUNK_SIZE, MAX_CHUNK_SIZE, MIN_CHUNK_SIZE,
};
pub use error::{CoreError, CoreResult};
pub use hash::{hash_file, hash_range};
pub use link::{code_to_bz_url, code_to_url, extract_code, is_valid_code};

/// FFI surface consumed by the Flutter app. Generated by
/// `flutter_rust_bridge_codegen`; not compiled unless the `bridge` feature is on.
#[cfg(feature = "bridge")]
pub mod api;

#[cfg(feature = "bridge")]
mod frb_generated;
